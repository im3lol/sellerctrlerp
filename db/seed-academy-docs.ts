const D = (
  slug: string, module: string, title: string, outcome: string,
  minutes: number, level: "basic" | "advanced", sortOrder: number, body: string,
) => ({ slug: `${slug}-guide`, module, title, outcome, minutes, level, sortOrder, kind: "doc", body });

