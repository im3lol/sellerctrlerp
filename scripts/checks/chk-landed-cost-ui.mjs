// Real UI writes exclusively to the disposable landed-cost clone.
import pg from "pg";
import { encode } from "next-auth/jwt";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
const url = new URL(process.env.DATABASE_URL);
if (!url.pathname.startsWith("/sellerctrl_landed_test_")) throw new Error("Landed-cost UI requires an isolated database");
const origin = "http://127.0.0.1:3012";
const { chromium } = createRequire(join(process.env.MCP_QA_PACKAGES, "package.json"))("playwright");
const pool = new pg.Pool({ connectionString: url.href });
const out = join(process.cwd(), ".next", "landed-cost-preview");
await mkdir(out, { recursive: true });
const check = (ok, name) => { if (!ok) throw new Error(`FAIL ${name}`); console.log(`PASS ${name}`); };
let browser;
try {
  const { rows: [u] } = await pool.query("select u.id,u.role,u.name,u.session_version,m.organization_id from users u join organization_members m on m.user_id=u.id join organizations o on o.id=m.organization_id where u.username like 'lcv_qa_%' and o.slug like 'lcv-test-%' order by u.created_at desc limit 1");
  if (!u) throw new Error("Run landed-cost integration fixtures first");
  await pool.query("update users set tour_dismissed=true where id=$1 and username like 'lcv_qa_%'", [u.id]);
  const cookie = "authjs.session-token";
  const token = await encode({ secret: process.env.AUTH_SECRET, salt: cookie, maxAge: 600, token: { sub: u.id, id: u.id, role: u.role, name: u.name, sv: u.session_version } });
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: "light" });
  await context.addCookies([{ name: cookie, value: token, url: origin, httpOnly: true }, { name: "locale", value: "en", url: origin }, { name: "erp_org", value: u.organization_id, url: origin }]);
  const page = await context.newPage(); page.setDefaultTimeout(60000);
  const errors = []; page.on("pageerror", e => errors.push(e.message));
  async function pick() {
    await page.getByPlaceholder("Search by supplier name…", { exact: true }).click();
    await page.getByRole("button", { name: /QA freight supplier/ }).click();
    await page.locator("label").filter({ hasText: "GRN-QA-1" }).locator('input[type="checkbox"]').check();
    await page.getByRole("checkbox", { name: "Apply cost to item LCV-B", exact: true }).waitFor();
  }
  await page.goto(`${origin}/purchases/landed-costs/new`, { waitUntil: "networkidle" });
  await pick();
  await page.locator('select:has(option[value="manual"])').selectOption("manual");
  await page.getByRole("checkbox", { name: "Apply cost to item LCV-A", exact: true }).uncheck();
  const perUnit = page.getByRole("spinbutton", { name: "Freight per unit for item LCV-B", exact: true });
  await perUnit.fill("9.5");
  const row = page.getByRole("row").filter({ hasText: "LCV-B" });
  check((await row.textContent()).includes("38.00"), "manual freight calculates quantity times per-unit cost");
  check(await page.getByRole("spinbutton", { name: "Freight per unit for item LCV-A", exact: true }).isDisabled(), "excluded item cannot receive a manual cost");
  check(await page.getByRole("columnheader", { name: "Cost", exact: true }).count() === 1, "selection column has the correct English label");
  check((await row.locator("td").nth(3).boundingBox()).width >= 235, "item names and cost history keep a readable column width");
  await page.screenshot({ path: join(out, "manual-selected-en.png"), fullPage: true });
  await page.getByRole("button", { name: "Save document", exact: true }).click();
  await page.waitForURL(/\/purchases\/landed-costs\/LCV-[^/]+$/);
  const number = decodeURIComponent(new URL(page.url()).pathname.split("/").at(-1));
  const { rows: [saved] } = await pool.query("select id,total_amount,status from landed_cost_vouchers where organization_id=$1 and number=$2", [u.organization_id, number]);
  const { rows: savedLines } = await pool.query("select i.code,l.allocated_amount from landed_cost_voucher_lines l join items i on i.id=l.item_id where l.voucher_id=$1", [saved.id]);
  check(saved.status === "DRAFT" && Number(saved.total_amount) === 38 && savedLines.length === 1 && savedLines[0].code === "LCV-B", "UI saves the selected product only as an unposted draft");
  await page.getByRole("button", { name: "Actions", exact: true }).click();
  await page.getByRole("menuitem", { name: "Edit draft", exact: true }).click();
  await page.waitForURL(/\/edit$/);
  await page.getByRole("spinbutton", { name: "Freight per unit for item LCV-B", exact: true }).waitFor();
  check(await page.getByRole("spinbutton", { name: "Freight per unit for item LCV-B", exact: true }).inputValue() === "9.5", "reopening the draft restores its saved per-unit freight");
  check(!await page.getByRole("checkbox", { name: "Apply cost to item LCV-A", exact: true }).isChecked(), "editing shows excluded products without reselecting them");
  await page.getByRole("spinbutton", { name: "Freight per unit for item LCV-B", exact: true }).fill("11");
  await page.getByRole("button", { name: "Save document", exact: true }).click();
  await page.waitForURL(/\/purchases\/landed-costs\/LCV-[^/]+$/);
  const { rows: [updated] } = await pool.query("select id,total_amount from landed_cost_vouchers where organization_id=$1 and number=$2", [u.organization_id, number]);
  check(updated.id === saved.id && Number(updated.total_amount) === 44, "draft editing replaces its allocation rather than creating another charge");
  await page.goto(`${origin}/purchases/landed-costs/new`, { waitUntil: "networkidle" });
  await pick();
  check(!await page.getByRole("checkbox", { name: "Apply cost to item LCV-B", exact: true }).isChecked(), "a product with an existing draft is not selected for duplicate loading");
  check(await page.getByText("Unposted draft", { exact: false }).count() > 0, "saved draft is visible as history without calling it posted");
  await page.locator("label").filter({ hasText: "GRN-QA-2" }).locator('input[type="checkbox"]').check();
  const prior = page.getByRole("row").filter({ hasText: "GRN-QA-2" }).filter({ hasText: "LCV-A" });
  await prior.getByRole("checkbox").waitFor();
  check(!await prior.getByRole("checkbox").isChecked() && (await prior.textContent()).includes("6.00"), "previously posted cost is shown and not selected automatically");
  await page.screenshot({ path: join(out, "prior-costs-en.png"), fullPage: true });
  await page.getByRole("checkbox", { name: "Show selected items only", exact: true }).check();
  check(await page.getByRole("row").filter({ hasText: "LCV-B" }).count() === 0, "excluded items can be hidden from the working table");
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "manual selection page has no document-wide mobile overflow");
  await context.addCookies([{ name: "locale", value: "ar", url: origin }]);
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "تكاليف استيراد جديدة", exact: true }).first().waitFor();
  check(await page.locator("html").getAttribute("dir") === "rtl", "landed-cost flow supports Arabic RTL");
  check(errors.length === 0, "interactive flow has no browser runtime errors");
  console.log(`Screenshots: ${out}; mutations only in ${url.pathname}`);
} finally { await browser?.close(); await pool.end(); }
