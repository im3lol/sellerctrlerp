async function main() {
  let added = 0, skipped = 0, revised = 0;
  for (const e of ENTRIES) {
    const [exists] = await db.select({ id: changelogEntries.id, body: changelogEntries.body }).from(changelogEntries)
      .where(eq(changelogEntries.title, e.title)).limit(1);
    if (exists) {
      if (e.revise && exists.body !== e.body) {
        await db.update(changelogEntries).set({ body: e.body, updatedAt: new Date() }).where(eq(changelogEntries.id, exists.id));
        revised++;
        console.log(`  ~ [${e.kind}] ${e.title}`);
      } else skipped++;
      continue;
    }
    await db.insert(changelogEntries).values({
      title: e.title, body: e.body, kind: e.kind, module: e.module,
      releasedAt: new Date(), isPublished: true,
    });
    added++;
    console.log(`  + [${e.kind}] ${e.title}`);
  }
  console.log(`\n${added} published, ${revised} revised, ${skipped} already there.`);
  process.exit(0);
}

main().catch((e) => { console.error(e); process.exit(1); });
